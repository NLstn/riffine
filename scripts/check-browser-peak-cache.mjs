import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {PeakCache, MAX_PEAK_BYTES, MAX_PEAK_ENTRIES} from '../web/public/practice/project-store.mjs';
const require = createRequire(new URL('../web/package.json',import.meta.url));
const {IDBFactory} = require('fake-indexeddb');
const indexedDB = new IDBFactory();
const first = new PeakCache({indexedDB}), reopened = new PeakCache({indexedDB});
const key = 'wave-v1-' + 'a'.repeat(64) + '-48000-2-8640000';
const bytes = new Uint8Array([1,2,3]);
assert.equal(await first.get(key), null);
await first.put(key, bytes);
assert.deepEqual(await reopened.get(key), bytes, 'cache must survive a fresh owner');
assert.equal(await reopened.get(key.replace('aaaa','bbbb')), null, 'changed content must miss');
assert.equal(await reopened.get(key.replace('wave-v1','wave-v2')), null, 'changed algorithm must miss');
await assert.rejects(first.put(key, new Uint8Array(MAX_PEAK_BYTES+1)));
const controller = new AbortController(); controller.abort();
await assert.rejects(first.put(key, new Uint8Array([9]), controller.signal));
assert.deepEqual(await reopened.get(key), bytes, 'cancelled publication changed peaks');
await assert.rejects(new PeakCache({indexedDB:null}).get(key));
for (let i=0;i<MAX_PEAK_ENTRIES+2;i++) await first.put(`entry-${i}`, bytes);
const count = await first.transaction('readonly', (store, done) => { const request=store.count(); request.onsuccess=()=>done(request.result); });
assert.equal(count, MAX_PEAK_ENTRIES);
console.log('Persistent peak cache: reopen, content/version misses, limits, cancellation, unavailable storage and eviction passed');
