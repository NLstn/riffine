// Execute actual browser Go/WASM store ports and shared core, not a JS schema.
import assert from 'node:assert/strict';
import {Worker} from 'node:worker_threads';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join, resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
const root=resolve(import.meta.dirname,'..'), temporary=await mkdtemp(join(tmpdir(),'riffine-saved-'));
const source=join(temporary,'source.wav');
const tone=spawnSync(`${root}/bin/riffine`,['tone','--out',source,'--seconds','0.2'],{encoding:'utf8'});
assert.equal(tone.status,0,tone.stderr);
const worker=new Worker(new URL('./browser-practice-node-worker.mjs',import.meta.url),{workerData:{source,name:'original.wav',wasm:`${root}/web/public/practice/core.wasm`,loader:`${root}/web/public/practice/wasm_exec.js`,storage:true}});
const pending=new Map();let next=0;
let readyResolve,readyReject;
const ready=new Promise((resolve,reject)=>{readyResolve=resolve;readyReject=reject;});
worker.on('message',message=>{if(message.type==='ready')readyResolve();else {const call=pending.get(message.id);if(call){pending.delete(message.id);call.resolve(message.response??message);}}});
worker.on('error',error=>{readyReject(error);for(const call of pending.values())call.reject(error);});
const timer=setTimeout(()=>{const error=new Error('Saved-project WASM check timed out');readyReject(error);for(const call of pending.values())call.reject(error);void worker.terminate();},30000);
const call=(request,file,document)=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});worker.postMessage({id,request:{version:1,...request},file,document});});
const host=(method,...args)=>new Promise((resolve,reject)=>{const id=++next;pending.set(id,{resolve,reject});worker.postMessage({type:'host_store',id,method,args});});
const successful=async(...args)=>{const result=await call(...args);assert.equal(result.error,undefined,result.error?.message);return result;};
try {
 await ready;
 await successful({type:'import',source:'source',document:'project'},'source');
 await successful({type:'command',command:{version:1,sequence:1,type:'set_parameters',speed:.6,pitch:3}});
 await successful({type:'command',command:{version:1,sequence:2,type:'set_annotations',annotations:{notes:'Keep my notes',regions:[{id:'phrase',label:'Verse',start:.02,end:.18,notes:'Phrase notes'}],markers:[{id:'section',kind:'section',label:'Verse entry',position:.02}],loops:[{id:'loop',label:'Verse',regionId:'phrase'}]}}});
 await successful({type:'command',command:{version:1,sequence:3,type:'set_practice_plans',practicePlans:[{id:'ladder',label:'60 to 100',regionId:'phrase',ladder:{startSpeed:.6,targetSpeed:1,incrementPoints:5,loopsPerStep:4,endBehavior:'stop'},cues:{version:1,countInBeats:4,restSeconds:2,clickLevel:.7,metronome:true,grid:{version:1,sourceBPM:120,beatsPerBar:4}}}]}});
 await successful({type:'save_as',document:'browser:fixture'});
 const original=(await host('read','browser:fixture')).result.document;
 const reopened=await successful({type:'open',source:'source',document:'browser:fixture'},'source');
 assert.equal(reopened.snapshot.sequence,1);assert.equal(reopened.snapshot.project.settings.speed,.6);
 assert.equal(reopened.snapshot.project.annotations.notes,'Keep my notes');
 assert.equal(reopened.snapshot.project.practicePlans[0].ladder.loopsPerStep,4);
 assert.equal(reopened.snapshot.project.practicePlans[0].cues.restSeconds,2);
 assert.equal(reopened.snapshot.project.practicePlans[0].cues.grid.sourceBPM,120);
 assert.match(reopened.snapshot.revision,/^[a-f0-9]{64}$/);
 await successful({type:'command',command:{version:1,sequence:2,type:'set_parameters',speed:.65}});
 const saved=await successful({type:'save'});
 assert.equal(saved.snapshot.sequence,2);assert.equal(saved.snapshot.revision,saved.saved.revision);
 assert.equal((await host('read',saved.saved.recovery)).result.document,original);
 const mismatched=await call({type:'open',source:'source',document:'browser:fixture'},'changed');
 assert.equal(mismatched.error.code,'identity_mismatch');
 const retained=await successful({type:'snapshot'});
 assert.equal(retained.snapshot.project.settings.speed,.65);
 const latest=(await host('read','browser:fixture')).result;
 const external=latest.document.replace('0.65','0.7');
 assert.equal((await host('update','browser:fixture',latest.revision,external)).error,undefined);
 const conflict=await call({type:'save'});
 assert.equal(conflict.error.code,'revision_conflict');
 assert.equal((await successful({type:'snapshot'})).snapshot.project.settings.speed,.65);
 assert((await successful({type:'export'})).document.includes('0.65'));
 await successful({type:'save_as',document:'browser:unsaved-copy'});
 await successful({type:'open',source:'source',document:saved.saved.recovery},'source');
 assert.equal((await successful({type:'snapshot'})).snapshot.project.settings.speed,.6);
 console.log(JSON.stringify({realGoWASMStore:true,sourceIdentityVerified:true,recoveryPreservesExactBytes:true,revisionConflictKeepsEdits:true,saveAsKeepsUnsavedEdits:true,saveDoesNotChangeSequence:true}));
} finally {clearTimeout(timer);await worker.terminate();await rm(temporary,{recursive:true,force:true});}
