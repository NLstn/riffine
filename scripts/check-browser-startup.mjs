import assert from 'node:assert/strict';
import {setImmediate as tick} from 'node:timers/promises';
import {prepareIsolatedReload} from '../web/src/service-worker.ts';
const never=new Promise(()=>{});
let claimed=0,registered;
const active={postMessage(message){assert.equal(message.type,'claim');claimed++;}};
const container={controller:null,ready:never,async register(path,options){registered={path,options};return {active};}};
let finished=false;
void prepareIsolatedReload(container,10).then(()=>{finished=true;});
await tick();assert(finished,'an installed worker with no controller blocked reload');assert.equal(claimed,1);
assert.equal(registered.path,'/offline-sw.js');assert.equal(registered.options.scope,'/');
let ready;
const first={...container,ready:new Promise(resolve=>{ready=resolve;}),register:async()=>({active:null,installing:null,waiting:null})};
finished=false;
const firstVisit=prepareIsolatedReload(first,1000).then(()=>{finished=true;});
await tick();assert(!finished,'first visit skipped worker installation');ready({active});await firstVisit;assert(finished);
await assert.rejects(prepareIsolatedReload({...first,ready:never},1),/timed out/);
const installing=new EventTarget();installing.state='installing';
const failed=prepareIsolatedReload({...first,ready:never,register:async()=>({active:null,installing})},1000);
await tick();installing.state='redundant';installing.dispatchEvent(new Event('statechange'));
await assert.rejects(failed,/Preparation failed/);
await assert.rejects(prepareIsolatedReload({...first,register:async()=>{throw new Error('Storage blocked');}},1),/Storage blocked/);
